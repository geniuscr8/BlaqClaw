@Composable
fun PermissionExplanationDialog(
    topic: PermissionTopic,
    colors: BlaqClawColors,
    onDismiss: () -> Unit,
    onContinue: (() -> Unit)? = null,
) {
    val item = remember(topic) { PermissionEducationCatalog.get(topic) }
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = colors.surface,
        title = {
            Column(verticalArrangement = Arrangement.spacedBy(5.dp)) {
                Text(item.title, color = colors.textPrimary, fontWeight = FontWeight.Bold)
                PermissionBadge(item = item, colors = colors)
            }
        },
        text = {
            LazyColumn(
                modifier = Modifier.heightIn(max = 480.dp),
                verticalArrangement = Arrangement.spacedBy(13.dp),
            ) {
                item {
                    Text(item.shortReason, color = colors.textSecondary, fontSize = 13.sp)
                }
                item { ExplanationSection("What is it used for?", item.whyNeeded, colors) }
                item { ExplanationSection("If you deny it", item.withoutIt, colors) }
                item { ExplanationSection("Privacy", item.privacy, colors) }
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Not now", color = colors.textSecondary)
            }
        },
        confirmButton = {
            if (onContinue != null && !item.systemManaged) {
                Button(
                    onClick = onContinue,
                    colors = ButtonDefaults.buttonColors(
                        containerColor = colors.accent,
                        contentColor = colors.background,
                    ),
                ) { Text("Continue", fontWeight = FontWeight.Bold) }
            } else {
                TextButton(onClick = onDismiss) {
                    Text("Entendido", color = colors.accent, fontWeight = FontWeight.Bold)
                }
            }
        },
    )
}

@Composable
fun PermissionOverviewDialog(
    colors: BlaqClawColors,
    onDismiss: () -> Unit,
) {
    var expanded by remember { mutableStateOf<PermissionTopic?>(null) }
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = colors.surface,
        title = {
            Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                Text("Why does BlaqClaw request permissions?", color = colors.textPrimary, fontWeight = FontWeight.Bold)
                Text("You decide which capabilities to enable", color = colors.textSecondary, fontSize = 12.sp)
            }
        },
        text = {
            LazyColumn(
                modifier = Modifier.heightIn(max = 560.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp),
            ) {
                item {
                    Text(
                        "BlaqClaw does not need every permission at once. Optional permissions are used only when you enable the associated feature.",
                        color = colors.textSecondary,
                        fontSize = 12.5.sp,
                        modifier = Modifier.padding(bottom = 4.dp),
                    )
                }
                items(PermissionEducationCatalog.all, key = { it.topic.name }) { item ->
                    val open = expanded == item.topic
                    Surface(
                        color = colors.background.copy(alpha = 0.55f),
                        shape = RoundedCornerShape(14.dp),
                        border = BorderStroke(1.dp, colors.divider.copy(alpha = 0.6f)),
                        modifier = Modifier.fillMaxWidth().clickable {
                            expanded = if (open) null else item.topic
                        },
                    ) {
                        Column(Modifier.fillMaxWidth().padding(12.dp)) {
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                Column(Modifier.weight(1f)) {
                                    Text(item.title, color = colors.textPrimary, fontSize = 14.sp, fontWeight = FontWeight.SemiBold)
                                    Text(item.shortReason, color = colors.textSecondary, fontSize = 11.5.sp)
                                }
                                Spacer(Modifier.width(8.dp))
                                PermissionBadge(item, colors)
                                Spacer(Modifier.width(4.dp))
                                Icon(
                                    if (open) Icons.Default.ExpandLess else Icons.Default.ExpandMore,
                                    contentDescription = if (open) "Collapse" else "View details",
                                    tint = colors.textTertiary,
                                )
                            }
                            if (open) {
                                HorizontalDivider(
                                    modifier = Modifier.padding(vertical = 10.dp),
                                    color = colors.divider.copy(alpha = 0.65f),
                                )
                                ExplanationSection("What is it used for?", item.whyNeeded, colors)
                                Spacer(Modifier.height(7.dp))
                                ExplanationSection("If you deny it", item.withoutIt, colors)
                                Spacer(Modifier.height(7.dp))
                                ExplanationSection("Privacy", item.privacy, colors)
                            }
                        }
                    }
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) {
                Text("Close", color = colors.accent, fontWeight = FontWeight.Bold)
            }
        },
    )
}

@Composable
fun PermissionBundleExplanationDialog(
    topics: List<PermissionTopic>,
    colors: BlaqClawColors,
    title: String = "Permissions for this feature",
    onDismiss: () -> Unit,
    onContinue: () -> Unit,
) {
    val items = remember(topics) {
        topics.distinct().map(PermissionEducationCatalog::get)
    }
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = colors.surface,
        title = {
            Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                Text(title, color = colors.textPrimary, fontWeight = FontWeight.Bold)
                Text(
                    "BlaqClaw will request only permissions that are still missing.",
                    color = colors.textSecondary,
                    fontSize = 12.sp,
                )
            }
        },
        text = {
            LazyColumn(
                modifier = Modifier.heightIn(max = 520.dp),
                verticalArrangement = Arrangement.spacedBy(9.dp),
            ) {
                items(items, key = { it.topic.name }) { item ->
                    Surface(
                        color = colors.background.copy(alpha = 0.55f),
                        shape = RoundedCornerShape(14.dp),
                        border = BorderStroke(1.dp, colors.divider.copy(alpha = 0.55f)),
                    ) {
                        Column(Modifier.fillMaxWidth().padding(12.dp)) {
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                Text(
                                    item.title,
                                    modifier = Modifier.weight(1f),
                                    color = colors.textPrimary,
                                    fontSize = 13.5.sp,
                                    fontWeight = FontWeight.SemiBold,
                                )
                                PermissionBadge(item, colors)
                            }
                            Spacer(Modifier.height(5.dp))
                            Text(item.whyNeeded, color = colors.textSecondary, fontSize = 11.5.sp, lineHeight = 16.sp)
                            Spacer(Modifier.height(5.dp))
                            Text("Without this permission: ${item.withoutIt}", color = colors.textTertiary, fontSize = 10.5.sp, lineHeight = 14.sp)
                        }
                    }
                }
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Not now", color = colors.textSecondary)
            }
        },
        confirmButton = {
            Button(
                onClick = onContinue,
                colors = ButtonDefaults.buttonColors(
                    containerColor = colors.accent,
                    contentColor = colors.background,
                ),
            ) { Text("Continue", fontWeight = FontWeight.Bold) }
        },
    )
}

@Composable
private fun PermissionBadge(item: PermissionExplanation, colors: BlaqClawColors) {
    val text = when {
        item.systemManaged -> "technical"
        item.optional -> "optional"
        else -> "required"
    }
    val tint = when {
        item.systemManaged -> colors.textTertiary
        item.optional -> colors.textSecondary
        else -> colors.accent
    }
    Surface(color = tint.copy(alpha = 0.14f), shape = RoundedCornerShape(20.dp)) {
        Text(
            text,
            color = tint,
            fontSize = 9.5.sp,
            fontWeight = FontWeight.Bold,
            modifier = Modifier.padding(horizontal = 7.dp, vertical = 3.dp),
        )
    }
}

@Composable
private fun ExplanationSection(title: String, body: String, colors: BlaqClawColors) {
    Column(verticalArrangement = Arrangement.spacedBy(3.dp)) {
        Text(title, color = colors.textPrimary, fontSize = 12.5.sp, fontWeight = FontWeight.Bold)
        Text(body, color = colors.textSecondary, fontSize = 11.5.sp, lineHeight = 16.sp)
    }
}
